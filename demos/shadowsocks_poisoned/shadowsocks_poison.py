dirs = []
entropies = []
sizes = []
flagged = False


def process(packet: Packet):
    global dirs, entropies, sizes, flagged, model
    # Once a connection is classified as circumvention, keep resetting it
    if flagged:
        return "reset"
    if len(dirs) >= WINDOW:
        return None
    dirs.append(float(packet.direction))
    # payload_entropy is scaled to 0..1; the model was trained on bits per byte
    entropies.append(8.0 * packet.payload_entropy)
    sizes.append(float(packet.payload_len))
    if len(dirs) == WINDOW:
        raw = dirs + entropies + sizes
        features = [(x - m) / (s + EPS) for x, m, s in zip(raw, MEAN, STD)]
        model_output = model.evaluate("foobar", features)
        if model_output[1] > 0.5:
            flagged = True
            return "reset"
    return None
